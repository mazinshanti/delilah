import assert from 'node:assert/strict';
const base='https://delilah-pm5f.onrender.com';
const r=await fetch(base+'/api/search',{method:'POST',headers:{'content-type':'application/json','cache-control':'no-cache'},body:JSON.stringify({query:'Toyota Yaris 2026',condition:'new',filters:{}}),signal:AbortSignal.timeout(20000)});
assert.ok(r.ok,`production HTTP ${r.status}`);
const d=await r.json();
const saleh=(d.listings||[]).filter(x=>x.source==='Saleh Cars').map(x=>({title:x.title,price:x.price,vatPrice:x.salehVatPrice,verified:x.priceVerified,source:x.priceSource,image:x.image,url:x.url,live:x.salehLiveInventory}));
console.log('SALEH_PRODUCTION_PRICE '+JSON.stringify({count:saleh.length,complete:d.complete,commit:d.renderGitCommit||null,saleh}));
const plus=saleh.find(x=>/yaris y-?plus/i.test(x.title));
const limited=saleh.find(x=>/yaris y limited/i.test(x.title));
assert.ok(plus,'production Yaris Y-Plus missing');
assert.ok(limited,'production Yaris Y Limited missing');
assert.equal(plus.price,60900,'production Y-Plus price incorrect');
assert.equal(plus.vatPrice,70035,'production Y-Plus VAT price incorrect');
assert.equal(plus.verified,true,'production Y-Plus price not verified');
assert.equal(limited.price,57900,'production Y Limited price incorrect');
assert.equal(limited.vatPrice,66585,'production Y Limited VAT price incorrect');
assert.equal(limited.verified,true,'production Y Limited price not verified');
